--QUESTIONS
--1)What are the top selling products by revenue and how much 
--revenue have the generated?
SELECT  p.product_name,
     '$ ' || SUM(o.quantity * p.unit_price) AS Total_revenue
FROM products_table AS P
INNER JOIN orders_table AS o ON o.product_id = p.product_id
GROUP BY p.product_name
ORDER BY SUM(o.quantity * p.unit_price) DESC
LIMIT 10;


--2)On which day of the week are chocolates most sold?
SELECT  o.order_dow,
       COUNT(order_id) AS no_of_orders,
	   CASE
	   WHEN o.order_dow = 0 THEN 'Sunday'  
	   WHEN o.order_dow = 1 THEN 'Monday'
	   WHEN o.order_dow = 2 THEN 'Tuesday'
	   WHEN o.order_dow = 3 THEN 'Wednesday'
	   WHEN o.order_dow = 4 THEN 'Thursday'
	   WHEN o.order_dow = 5 THEN 'Friday' 
	   ELSE 'Saturday'
	   END AS days_of_week
FROM orders_table AS o
INNER JOIN products_table AS p ON p.product_id = o.product_id
WHERE p.product_name  ILIKE '%Chocolate%'
GROUP BY o.order_dow
ORDER BY no_of_orders DESC
LIMIT 1;
INSIGHT; Chocolates are sold mostly on Sundays


--3)do we have any department where we have over $15million in revenue 
--and what is the profit?
SELECT d.department,
  '$' || SUM(p.unit_price * o.quantity) AS Total_reveue,
 '$' || SUM((p.unit_price - p.unit_cost) * o.quantity) AS Profit
FROM orders_table AS o
INNER JOIN products_table AS p ON p.product_id = o.product_id
INNER JOIN departments AS d ON d.department_id = p.department_id
GROUP BY d.department
HAVING SUM (o.quantity * p.unit_price) > 15000000 ;

--4)IS it true customers buy more alcoholic products on xmas day 2019?
SELECT d.department,
      COUNT (d.department_id) AS no_of_patronage,
	'$' ||   SUM(p.unit_price * o.quantity) AS Total_revenue
FROM departments AS d
INNER JOIN products_table AS p ON p.department_id = d.department_id
INNER JOIN orders_table AS o  ON o.product_id = p.product_id
WHERE o.order_date = '2019-12-25'
GROUP BY d.department
ORDER BY no_of_patronage DESC;



--5)Which year did Instacart generate the most profit?
SELECT EXTRACT(YEAR FROM order_date) AS Years,
 '$' || SUM((p.unit_price - p.unit_cost) * o.quantity) AS PROFIT
FROM orders_table AS o
INNER JOIN products_table AS p ON p.product_id = o.product_id
GROUP BY  EXTRACT(YEAR FROM order_date)
ORDER BY SUM((p.unit_price - p.unit_cost) * o.quantity) DESC
LIMIT 1;

--6)How long has it been since the last cheese order?
