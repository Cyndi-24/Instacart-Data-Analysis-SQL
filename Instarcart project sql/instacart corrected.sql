--9)Which 3 products do people buy at night(2020-2022)
SELECT p.product_name,
        COUNT (order_id) AS no_of_orders
FROM orders_table AS o
INNER JOIN products_table AS p ON p.product_id = o.product_id
WHERE  o.order_date BETWEEN '2020-01-01' AND '2022-12-31' 
      AND o.order_hour_of_day IN ('18','19','20','21','22','23','0','1','2','3','4','5')	
